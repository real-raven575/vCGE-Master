// Builds src/vendor/zip-towns/zipTowns.js, the offline US ZIP code -> town table (part of `npm run vendor`, or `node scripts/zip-towns.mjs`).
// Source: the zipcodes npm package (BSD; its US data comes from the Free Zipcode Database, federalgovernmentzipcodes.us),
// pinned in package.json. The output is committed, so the app needs no install step and no network for it.
// Format (one string, read by mod05-form/zipTowns.js): "Town,ST|Town,ST|..." then a newline, then one entry per ZIP in
// order: the gap from the previous ZIP in base 36, then ":" and the town's index in base 36 when it differs from the
// previous ZIP's town.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { codes } = require('zipcodes/lib/codes.js');
const OUT = path.join(ROOT, 'src', 'vendor', 'zip-towns');

const zips = Object.keys(codes).filter(z => /^\d{5}$/.test(z) && codes[z].city && codes[z].state).sort();
const towns = [], index = new Map(), entries = [];
let lastZip = 0, lastTown = -1;
for (const zip of zips) {
    const { city, state } = codes[zip];
    const key = `${city.trim()},${state.trim()}`;
    if (/[|,\n]/.test(city)) throw new Error(`unexpected character in ${key}`);
    if (!index.has(key)) { index.set(key, towns.length); towns.push(key); }
    const t = index.get(key);
    entries.push((Number(zip) - lastZip).toString(36) + (t === lastTown ? '' : `:${t.toString(36)}`));
    lastZip = Number(zip);
    lastTown = t;
}
const data = `${towns.join('|')}\n${entries.join(' ')}`;
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'zipTowns.js'),
    `// Generated by scripts/zip-towns.mjs from zipcodes ${require('zipcodes/package.json').version} (BSD, LICENSE-zipcodes.txt). ` +
    `${zips.length} US ZIP codes. Do not edit.\nexport const ZIP_TOWNS = ${JSON.stringify(data)};\n`);
fs.copyFileSync(require.resolve('zipcodes/LICENSE'), path.join(OUT, 'LICENSE-zipcodes.txt'));
console.log(`zip-towns: ${zips.length} ZIP codes, ${towns.length} towns, ${data.length} characters`);
