// Builds the tour's pilot art from Creative's checked SVG files (CRTV-0059 finals) into the app's own code:
//   node scripts/tour-art.mjs <folder with tour/*.svg>
// Writes src/modules/mod01-shell/tourArtSvgs.js (the drawings as inline markup) and tour-art.css (their styles: the page's
// CSP drops a <style> inside markup, so each drawing's rules move to a bundled stylesheet). Each drawing loses its <title>,
// role and size (the slot is aria-hidden and sizes it), and its ids get the file's name in front so no two drawings share one.
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/tour-art.mjs <folder>'); process.exit(1); }
const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/modules/mod01-shell');
const files = fs.readdirSync(path.join(dir, 'tour')).filter(f => f.endsWith('.svg')).sort();
const svgs = {}, styles = [];
for (const f of files) {
    const key = f.replace(/^\d+-[a-z]+-/, '').replace(/\.svg$/, '');           // 01-scan-iris.svg -> iris
    const tag = `ta-${key}`;
    let m = fs.readFileSync(path.join(dir, 'tour', f), 'utf8').trim();
    m = m.replace(/<style>([\s\S]*?)<\/style>/g, (_, css) => { styles.push(`/* ${f} */\n${css}`); return ''; });
    m = m.replace(/<title[^>]*>[\s\S]*?<\/title>/g, '');
    m = m.replace(/\s(width|height|role|aria-labelledby|xmlns:c2pa)="[^"]*"/g, (all, name, offset) => (offset < m.indexOf('>') ? '' : all));
    // Ids that are not already unique to this drawing (Flipside's gradients "ff", "fb") get its name in front
    const ids = [...m.matchAll(/\sid="([^"]+)"/g)].map(x => x[1]).filter(id => !id.includes(f.replace(/\.svg$/, '').replace(/^\d+-/, '')));
    for (const id of ids) m = m.replaceAll(`id="${id}"`, `id="${tag}-${id}"`).replaceAll(`url(#${id})`, `url(#${tag}-${id})`).replaceAll(`href="#${id}"`, `href="#${tag}-${id}"`);
    svgs[key] = m;
}
const header = '// Generated by scripts/tour-art.mjs from Creative\'s CRTV-0059 finals (tour-art-v1). Do not edit by hand.\n';
fs.writeFileSync(path.join(out, 'tourArtSvgs.js'), `${header}export const TOUR_SVGS = Object.freeze(${JSON.stringify(svgs, null, 4)});\n`);
fs.writeFileSync(path.join(out, 'tour-art.css'), `/* Generated by scripts/tour-art.mjs from Creative's CRTV-0059 finals (tour-art-v1). Do not edit by hand.
   Each drawing's own rules: round line ends, and a slow sway (4.5 s) that stops under reduced motion. */\n${styles.join('\n')}\n`);
console.log(`${Object.keys(svgs).join(', ')}: ${files.length} drawings`);
