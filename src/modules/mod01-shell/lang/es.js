const patterns = [
    // "Step 1 of 6", "Step 2 of 5 · Read"
    [/^Step (\d+) of (\d+)$/, 'Paso $1 de $2'],
    [/^Step (\d+) of (\d+) · (.+)$/, (m, line) => `Paso ${m[1]} de ${m[2]} · ${line(m[3]) ?? m[3]}`],
    // Swatches and themes: "Pumpkin stock", "Pumpkin theme, Oct (Seasonal)", "Shutout theme (Team vCGE)"
    [/^(.+) stock$/, (m, line) => (line(m[1]) ? `Cartulina ${line(m[1])}` : null)],
    [/^(.+?) theme(?:, (.+?))?(?: \((.+)\))?$/, (m, line) => {
        const name = line(m[1]) ?? (NAMES[m[1]] || m[1] === 'Herd' ? m[1] : null);
        if (!name) return null;
        const when = m[2] ? `, ${line(m[2]) ?? m[2]}` : '';
        const group = m[3] ? ` (${line(m[3]) ?? m[3]})` : '';
        return `Tema ${name}${when}${group}`;
    }],
    // "Contrast 15 to 1"
    [/^Contrast (\d+) to 1$/, 'Contraste $1 a 1'],
    // "3.5 cm wide"
    [/^(\d+)(?:\.(\d+))? cm wide$/, (m) => `${m[1]}${m[2] ? `,${m[2]}` : ''} cm de ancho`],
    // "phone 1", "Remove email 2", "website 1 type"
    [/^(phone|email|website) (\d+)( type)?$/, (m) => `${m[3] ? 'tipo de ' : ''}${{ phone: 'teléfono', email: 'correo', website: 'sitio web' }[m[1]]} ${m[2]}`],
    [/^Remove (phone|email|website) (\d+)$/, (m) => `Quitar ${{ phone: 'teléfono', email: 'correo', website: 'sitio web' }[m[1]]} ${m[2]}`],
    // A picture drop-down's button: "Dot shape: Square", "Colour vision: Typical" (both halves known, else English)
    [/^([^:]+): (.+)$/, (m, line) => (line(m[1]) && line(m[2]) ? `${line(m[1])}: ${line(m[2])}` : null)]
];

